/**
 * A watercolour ink wash.
 *
 * Built in two passes rather than one flat shape, which is what separates a
 * wash from a sticker: a translucent, mottled, heavily bled halo, and over it
 * a solid body whose edge bleeds but whose fill stays even. Anything sitting
 * on the blot sits on that solid body, so its contrast does not depend on
 * where the pigment happened to pool.
 *
 * Both outlines are generated Catmull-Rom curves through irregular polar
 * points with three overlapping harmonics; the filters then displace the
 * edges with fractal noise so they tear the way ink does on paper.
 *
 * Purely decorative and hidden from assistive technology.
 */
export function InkSpill({
  className,
  /** Thrown-off droplets. Drop them at small sizes, where they read as dirt. */
  droplets = true,
}: {
  className?: string;
  droplets?: boolean;
}) {
  return (
    <svg
      viewBox="0 0 400 260"
      preserveAspectRatio="none"
      fill="currentColor"
      aria-hidden="true"
      focusable="false"
      className={cn("block", className)}
    >
      <g filter="url(#ink-wash)" opacity="0.42">
        <path d={HALO} />
        {droplets ? DROPS.map((d) => <path key={d.slice(0, 12)} d={d} />) : null}
      </g>

      <g filter="url(#ink-bleed)">
        <path d={BODY} />
      </g>
    </svg>
  );
}
